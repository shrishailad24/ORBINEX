/**
 * Helper: Find a dataset by ID
 */
export function getDatasetById(id: string): DatasetRecord | undefined {
  return UNIFIED_DATASET_REGISTRY.find((d) => d.id === id);
}

/**
 * Helper: Filter datasets by category
 */
export function getDatasetsByCategory(category: DatasetCategory): DatasetRecord[] {
  return UNIFIED_DATASET_REGISTRY.filter((d) => d.category === category);
}

/**
 * Helper: Search datasets by keyword (name, provider, description, use cases)
 */
export function searchDatasets(query: string, category?: DatasetCategory): DatasetRecord[] {
  const q = query.trim().toLowerCase();
  return UNIFIED_DATASET_REGISTRY.filter((d) => {
    if (category && d.category !== category) return false;
    if (!q) return true;
    return (
      d.name.toLowerCase().includes(q) ||
      d.provider.toLowerCase().includes(q) ||
      d.description.toLowerCase().includes(q) ||
      d.license.toLowerCase().includes(q) ||
      d.primaryUseCases.some((u) => u.toLowerCase().includes(q))
    );
  });
}
